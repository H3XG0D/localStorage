"""Тексты инструкций для загрузки чека/видео подтверждения оплаты."""

PDF_RECEIPT_PROMPT = (
    "Пришлите в бот <b>чек об оплате в формате PDF</b> — отправьте файл .pdf в чат."
)

VIDEO_RECEIPT_PROMPT = (
    "PDF не принят. Пришлите в бот <b>видео</b> подтверждения оплаты (MP4, MOV и т.д.) — "
    "отправьте видео в чат (не «кружок»)."
)

VIDEO_RECEIPT_INSTRUCTIONS_HTML = """
<b>Как снять видео (30–60 сек, до 20 МБ)</b>

1. <b>Только запись экрана</b> (не с камеры).
2. На экране должно быть видно <b>только</b>:
   • главный экран телефона (без лишних приложений);
   • приложение <b>вашего банка</b>;
   • экран <b>успешного перевода</b> (сумма, получатель, статус «выполнено»).
3. <b>Нельзя показывать:</b> мессенджеры, соцсети, галерею, другие вкладки, PIN/пароль, посторонние уведомления.
4. Видео <b>непрерывное</b>: от открытия банка до экрана успеха, без монтажа.

<b>iPhone (iOS 11+):</b>
Настройки → Пункт управления → «+ Запись экрана».
Control Center → «Запись экрана» (микрофон <b>выкл</b>) → запись → банк → оплата → успех → стоп.
Отправьте в бот как <b>видео</b> или загрузите на сайте.

<b>Android:</b>
Шторка → «Запись экрана» (микрофон выкл) → банк → оплата → успех → стоп.
Отправьте файл в бот или загрузите на сайте.

Форматы: MP4, MOV, WebM, MKV (до 20 МБ).
""".strip()


def receipt_success_status_request_message(order_id: str) -> str:
    """Повторный PDF: в первом чеке перевод ещё «ожидается» / «в обработке»."""
    return (
        "📎 <b>Нужен обновлённый чек</b>\n\n"
        f"🆔 Заявка: <code>{order_id}</code>\n\n"
        "В присланном ранее PDF перевод ещё в статусе "
        "<b>«ожидается»</b> или <b>«в обработке»</b>.\n\n"
        "Когда в банке статус станет <b>«Выполнено»</b> — скачайте новый PDF-чек "
        "и пришлите его сюда как документ <b>.pdf</b>."
    )


def receipt_request_message(order_id: str, req_type: int) -> str:
    """Сообщение пользователю о необходимости чека/видео."""
    if req_type == 3:
        header = "📎 <b>PDF не принят — требуется видео</b>"
        body = f"{VIDEO_RECEIPT_PROMPT}\n\n{VIDEO_RECEIPT_INSTRUCTIONS_HTML}"
    else:
        header = "📎 <b>Требуется подтверждение оплаты</b>"
        body = PDF_RECEIPT_PROMPT
    return (
        f"{header}\n\n"
        f"🆔 Заявка: <code>{order_id}</code>\n\n"
        f"{body}"
    )


def receipt_rejected_message(req_type: int, *, merchant_rejected: bool = False) -> str:
    """Ответ при отклонении чека/видео."""
    if req_type == 3:
        return (
            "❌ Видео не принято. Запишите экран заново: только банк и экран успешной оплаты. "
            "Формат MP4/MOV, до 20 МБ."
        )
    if merchant_rejected:
        return (
            "❌ Чек не принят платёжной системой. Убедитесь, что это <b>официальный PDF-чек "
            "из банка</b> (с суммой и статусом «выполнено»).\n\n"
            "Если оплата прошла, но ошибка повторяется — дождитесь подтверждения от системы "
            "или запишите видео экрана оплаты."
        )
    return (
        "❌ PDF не принят. Отправьте <b>файл .pdf</b> как документ (не фото). "
        "Убедитесь, что это официальный чек из банка."
    )
